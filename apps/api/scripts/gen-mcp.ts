// Generates the MCP server's tools from openapi.yaml (D190): one tool per operation a personal
// token may call, named by its operationId, with an input schema of its path and query parameters
// and its body. Operations only a desk session may call (managing tokens) are listed apart. Run by
// `pnpm gen`; the output is never edited by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

type Schema = Record<string, unknown>;
interface Parameter {
  name: string;
  in: "path" | "query" | "header";
  required?: boolean;
  description?: string;
  schema?: Schema;
}
interface Operation {
  operationId: string;
  summary?: string;
  description?: string;
  security?: Record<string, unknown>[];
  parameters?: (Parameter | { $ref: string })[];
  requestBody?: { required?: boolean; content?: { "application/json"?: { schema?: Schema } } };
  "x-anr-who"?: string;
}
interface Spec {
  paths: Record<string, Record<string, unknown>>;
  components: { schemas: Record<string, Schema>; parameters: Record<string, Parameter> };
}

const METHODS = ["get", "post", "put", "delete", "patch"] as const;
/** Words in an operationId that mean the call decides, removes or stops something. */
const DESTRUCTIVE =
  /^(approve|return|pullBack|choose|uphold|reject|revoke|cancel|drain|pause|unload|remove|delete|archive|reset|replace)/i;

const here = (p: string) => new URL(p, import.meta.url);
const spec = parse(readFileSync(here("../openapi.yaml"), "utf8")) as Spec;

const SCHEMA_REF = "#/components/schemas/";
/** Copies a schema, pointing its component references at `$defs` and collecting them. */
function localise(schema: unknown, defs: Set<string>): unknown {
  if (Array.isArray(schema)) return schema.map((s) => localise(s, defs));
  if (!schema || typeof schema !== "object") return schema;
  const out: Schema = {};
  for (const [k, v] of Object.entries(schema)) {
    if (k === "$ref" && typeof v === "string" && v.startsWith(SCHEMA_REF)) {
      const name = v.slice(SCHEMA_REF.length);
      if (!defs.has(name)) {
        defs.add(name);
        localise(spec.components.schemas[name], defs);
      }
      out.$ref = `#/$defs/${name}`;
    } else out[k] = localise(v, defs);
  }
  return out;
}

const parameter = (p: Parameter | { $ref: string }): Parameter => {
  if ("$ref" in p) {
    const found = spec.components.parameters[p.$ref.replace("#/components/parameters/", "")];
    if (!found) throw new Error(`no parameter ${p.$ref}`);
    return found;
  }
  return p;
};

const tools: unknown[] = [];
const browserOnly: unknown[] = [];
for (const [path, item] of Object.entries(spec.paths)) {
  if (!path.startsWith("/desk/")) continue;
  const shared = (item.parameters as Operation["parameters"]) ?? [];
  for (const method of METHODS) {
    const op = item[method] as Operation | undefined;
    if (!op) continue;
    const summary = op.summary ?? op.operationId;
    if (!op.security?.some((s) => "personalToken" in s)) {
      browserOnly.push({
        name: op.operationId,
        method: method.toUpperCase(),
        path,
        title: summary,
      });
      continue;
    }
    const defs = new Set<string>();
    const properties: Schema = {};
    const required: string[] = [];
    const params = [...shared, ...(op.parameters ?? [])].map(parameter);
    for (const p of params) {
      if (p.in === "header") continue;
      properties[p.name] = localise(
        {
          ...(p.schema ?? { type: "string" }),
          ...(p.description && { description: p.description }),
        },
        defs,
      );
      if (p.required || p.in === "path") required.push(p.name);
    }
    const body = op.requestBody?.content?.["application/json"]?.schema;
    if (body) {
      properties.body = localise(body, defs);
      if (op.requestBody?.required) required.push("body");
    }
    const $defs = Object.fromEntries(
      [...defs].sort().map((name) => [name, localise(spec.components.schemas[name], new Set())]),
    );
    const who = path.startsWith("/desk/admin/")
      ? "platform-admin"
      : (op["x-anr-who"] ?? (path.includes("{newsroom}") ? "member" : "anyone"));
    tools.push({
      name: op.operationId,
      method: method.toUpperCase(),
      path,
      title: summary,
      description: [summary, op.description].filter(Boolean).join("\n\n"),
      who,
      readOnly: method === "get",
      destructive: method === "delete" || DESTRUCTIVE.test(op.operationId),
      inputSchema: {
        type: "object",
        properties,
        ...(required.length > 0 && { required }),
        additionalProperties: false,
        ...(defs.size > 0 && { $defs }),
      },
    });
  }
}

const out = `// Generated by scripts/gen-mcp.ts from openapi.yaml (D190). Do not edit; run \`pnpm gen\`.

/** One MCP tool: an API operation a personal token may call. */
export interface McpTool {
  /** The operation's operationId. */
  name: string;
  method: "GET" | "POST" | "PUT" | "DELETE" | "PATCH";
  /** The operation's path, with \`{name}\` for each path parameter. */
  path: string;
  title: string;
  description: string;
  /** Who may call it: any member of the newsroom, its Editor-in-Chief, the platform admin, or anyone signed in. */
  who: "member" | "editor-in-chief" | "platform-admin" | "anyone";
  readOnly: boolean;
  destructive: boolean;
  /** Path and query parameters by name, and the request body as \`body\`. */
  inputSchema: Record<string, unknown>;
}

/** An operation only a desk session through Access may call, never a token (D191). */
export interface BrowserOnlyOperation {
  name: string;
  method: string;
  path: string;
  title: string;
}

export const MCP_TOOLS: readonly McpTool[] = ${JSON.stringify(tools, null, 2)};

export const BROWSER_ONLY: readonly BrowserOnlyOperation[] = ${JSON.stringify(browserOnly, null, 2)};
`;
writeFileSync(here("../src/generated/mcp-tools.ts"), out);
console.log(`generated ${tools.length} MCP tools, ${browserOnly.length} browser-only operations`);
