// Writes the dashboards and rules of ops/ into infra/observability/ (`pnpm gen`; `pnpm gen:check`
// fails on drift). Every file it writes is generated and never edited by hand.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { stringify } from "yaml";
import { DASHBOARDS, toGrafana } from "./dashboards.ts";
import { ALERTS, type Alert, RECORDING_RULES } from "./rules.ts";

const root = fileURLToPath(new URL("../../../infra/observability/", import.meta.url));
const HEADER = "# Generated by packages/telemetry/ops/gen.ts: edit that, then `pnpm gen`.\n";

function write(path: string, text: string) {
  mkdirSync(`${root}${path.slice(0, path.lastIndexOf("/"))}`, { recursive: true });
  writeFileSync(`${root}${path}`, text);
}
const yaml = (value: unknown) => HEADER + stringify(value, { lineWidth: 0 });

// Dashboards: one file each; a removed dashboard's file goes too.
const dashboards = "grafana/dashboards";
mkdirSync(`${root}${dashboards}`, { recursive: true });
for (const file of readdirSync(`${root}${dashboards}`))
  if (file.endsWith(".json")) rmSync(`${root}${dashboards}/${file}`);
for (const d of DASHBOARDS)
  write(`${dashboards}/${d.uid}.json`, `${JSON.stringify(toGrafana(d), null, 2)}\n`);

// Recording rules: loaded by Prometheus (prometheus.yaml's rule_files).
write(
  "prometheus/rules/slo.yaml",
  yaml({ groups: [{ name: "anr-slo", interval: "1m", rules: RECORDING_RULES }] }),
);

const labels = (a: Alert) => ({ severity: a.severity });

// The alerts as Prometheus rules, for promtool's tests only: Prometheus never loads this file.
write(
  "prometheus/alerts/alerts.yaml",
  yaml({
    groups: [
      {
        name: "anr",
        rules: ALERTS.map((a) => ({
          alert: a.name,
          expr: a.expr,
          for: a.for,
          labels: labels(a),
          annotations: { summary: a.summary },
        })),
      },
    ],
  }),
);

// The same alerts as Grafana-managed rules. Each query returns only firing series, so no data is
// all well (absences are written into the queries); a failed query is an error alert.
write(
  "grafana/provisioning/alerting/rules.yaml",
  yaml({
    apiVersion: 1,
    groups: [
      {
        orgId: 1,
        name: "anr",
        folder: "ANR",
        interval: "1m",
        rules: ALERTS.map((a) => ({
          uid: `anr-${a.name.replace(/[A-Z]/g, (c, i) => (i ? "-" : "") + c.toLowerCase())}`,
          title: a.name,
          condition: "B",
          data: [
            {
              refId: "A",
              relativeTimeRange: { from: 600, to: 0 },
              datasourceUid: "prometheus",
              model: {
                refId: "A",
                datasource: { type: "prometheus", uid: "prometheus" },
                expr: `(${a.expr}) * 0 + 1`,
                instant: true,
                range: false,
              },
            },
            {
              refId: "B",
              datasourceUid: "__expr__",
              model: {
                refId: "B",
                datasource: { type: "__expr__", uid: "__expr__" },
                type: "threshold",
                expression: "A",
                conditions: [{ evaluator: { type: "gt", params: [0] } }],
              },
            },
          ],
          noDataState: "OK",
          execErrState: "Error",
          for: a.for,
          labels: labels(a),
          annotations: { summary: a.summary },
          isPaused: false,
        })),
      },
    ],
  }),
);
