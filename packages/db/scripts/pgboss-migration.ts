// Writes the pg-boss schema as a dbmate migration, so anr_migrator installs it and the workers
// run without CREATE rights (they start pg-boss with migrate: false).
//   pnpm --filter @anr/db pgboss:migration <migration file>
// For a pg-boss upgrade, write a new migration from getMigrationPlans() the same way.
import { readFileSync, writeFileSync } from "node:fs";
import { getConstructionPlans } from "pg-boss";
import { PGBOSS_SCHEMA } from "../src/boss.ts";

const file = process.argv[2];
if (!file) throw new Error("usage: pgboss-migration <migration file>");

// pg-boss wraps its plan in BEGIN ... COMMIT; dbmate already runs each migration in one
// transaction, and an inner COMMIT would end it early. The advisory lock and SET LOCALs stay.
const plan = getConstructionPlans(PGBOSS_SCHEMA)
  .trim()
  .replace(/^BEGIN;/, "")
  .replace(/COMMIT;$/, "")
  .trim();
if (/\b(BEGIN|COMMIT);/.test(plan.replace(/\$\$[\s\S]*?\$\$/g, ""))) {
  throw new Error("unexpected transaction control left in the pg-boss plan");
}

const runtime = "anr_app, anr_system";
const sql = `-- migrate:up
-- Generated by scripts/pgboss-migration.ts from pg-boss ${pgBossVersion()}; do not edit.
${plan}

-- The runtime roles only move jobs: no DDL (no partitioned queues, no reindex, no queue stats).
grant usage on schema ${PGBOSS_SCHEMA} to ${runtime};
grant select, insert, update, delete on all tables in schema ${PGBOSS_SCHEMA} to ${runtime};
grant usage, select on all sequences in schema ${PGBOSS_SCHEMA} to ${runtime};
grant execute on all functions in schema ${PGBOSS_SCHEMA} to ${runtime};
-- So upgrade migrations (anr_migrator) grant the runtime roles what they add.
alter default privileges for role anr_migrator in schema ${PGBOSS_SCHEMA}
  grant select, insert, update, delete on tables to ${runtime};
alter default privileges for role anr_migrator in schema ${PGBOSS_SCHEMA}
  grant usage, select on sequences to ${runtime};
alter default privileges for role anr_migrator in schema ${PGBOSS_SCHEMA}
  grant execute on functions to ${runtime};

-- migrate:down
drop schema ${PGBOSS_SCHEMA} cascade;
`;
writeFileSync(file, sql);

function pgBossVersion(): string {
  const pkg = new URL(import.meta.resolve("pg-boss/package.json"));
  return (JSON.parse(readFileSync(pkg, "utf8")) as { version: string }).version;
}
